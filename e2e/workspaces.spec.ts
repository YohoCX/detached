import { expect, open, repoRow, sidebar, test } from './fixture'

test('workspaces: several on at once, each with its folders; rename, turn off, delete', async ({ page, fx }) => {
  await open(page)
  const side = sidebar(page)
  const picker = page.getByRole('dialog', { name: 'Workspaces' })
  const toggle = (name: string) => picker.getByRole('checkbox').filter({ hasText: name }).click()
  const widget = page.getByTitle('Workspaces')
  await widget.click()
  await picker.getByPlaceholder('New workspace').fill('Home')
  await page.keyboard.press('Enter')
  await expect(side.locator('.workspace')).toHaveText(['Default', 'Home'])
  await page.keyboard.press('Escape')
  await expect(picker).toHaveCount(0)

  await page.evaluate((pick) => (window.__E2E__.pick = pick), [fx.repo('lib')])
  await side.locator('.workspace').filter({ hasText: 'Home' }).hover()
  await page.getByTitle('Add folder to Home').click()
  await expect(repoRow(page, 'lib')).toHaveCount(2)

  await widget.click()
  await toggle('Default')
  await expect(side.locator('.workspace')).toHaveCount(0)
  await expect(side.locator('.repo .name')).toHaveText(['lib'])
  await expect(widget).toHaveText('Home')

  await picker.getByRole('checkbox').filter({ hasText: 'Home' }).hover()
  await picker.getByTitle('Rename Home').click()
  await picker.getByLabel('Workspace name').fill('Family')
  await page.keyboard.press('Enter')
  await expect(widget).toHaveText('Family')
  await toggle('Family')
  await expect(side).toContainText('No workspace is on')
  await expect(widget).toHaveText('No workspace')

  await picker.getByRole('checkbox').filter({ hasText: 'Family' }).hover()
  await picker.getByTitle('Delete Family').click()
  await expect(picker.getByRole('checkbox')).toHaveText([/Default/])
})

test('related files nest under their main file; the switch flattens the tree', async ({ page, fx }) => {
  fx.commit(fx.repo('lib'), 'nest', { 'src/a.ts': '', 'src/a.spec.ts': '', 'src/b.ts': '' })
  await open(page, 'lib')
  await page.keyboard.press('ControlOrMeta+1')
  const tree = page.locator('[role=tree]')
  const names = () => tree.locator('[role=treeitem] .ellipsis')
  await tree.getByRole('treeitem', { name: 'src', exact: true }).click()
  await expect(names()).toContainText(['src', 'a.ts', 'b.ts'])
  await expect(tree.getByRole('treeitem', { name: 'a.spec.ts', exact: true })).toHaveCount(0)
  await tree.getByRole('treeitem', { name: 'a.ts', exact: true }).locator('.chev').click()
  await expect(names()).toContainText(['src', 'a.ts', 'a.spec.ts', 'b.ts'])
  await page.getByTitle('Nest related files').click()
  await expect(names()).toContainText(['src', 'a.spec.ts', 'a.ts', 'b.ts'])
})
